function makeBaseEl(partial: Partial<CanvasElement> & Pick<CanvasElement, 'type' | 'x' | 'y' | 'width' | 'height'>): CanvasElement {
  return {
    id: createId(partial.type),
    angle: 0,
    opacity: 1,
    strokeColor: '#0F172A',
    fillColor: 'transparent',
    fillStyle: 'hachure',
    strokeWidth: 2,
    strokeStyle: 'solid',
    roughness: 1.2,
    cornerRadius: 0,
    seed: Math.floor(Math.random() * 100000) + 1,
    fontFamily: 'sketch',
    fontSize: 20,
    fontWeight: 'normal',
    fontStyle: 'normal',
    textAlign: 'center',
    textColor: '#0F172A',
    ...partial,
  };
}

